"""
The migration and the ORM must not drift apart.

Two descriptions of one schema exist: `src/models.py`, which the service queries
through, and `alembic/versions/0001_*.py`, which creates the tables. Nothing forces
them to agree, and the repository's own history is what happens when nothing forces
agreement -- four sources describing one API, disagreeing four ways, with the code
right and every document wrong.

`alembic check` compares the ORM metadata against the live migrated database and fails
when a model has a column, index or constraint the migration does not create. It caught
four real disagreements the first time it ran here: two `DESC` indexes declared without
their ordering, and two GIN indexes written as raw SQL in the migration and therefore
invisible to the comparison.

This test is that check, so the gate runs wherever the suite does.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

SERVICE_ROOT = Path(__file__).resolve().parents[1]


def _alembic_config(database_url: str):
    from alembic.config import Config

    config = Config(str(SERVICE_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(SERVICE_ROOT / "alembic"))
    os.environ["MEMORY_DATABASE_URL"] = database_url
    return config


async def test_the_orm_matches_the_migrated_schema(engine, database_url) -> None:
    """
    No pending operations, which means no drift.

    A failure here is not "regenerate the migration" -- it is a question about which of
    the two is right. The migration created what is in the database; the model is what
    the code believes. They disagree, and only one is a bug.
    """
    from alembic import command
    from alembic.util.exc import AutogenerateDiffsDetected

    config = _alembic_config(database_url)
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(
            "The ORM in src/models.py and the Alembic migration describe different "
            f"schemas:\n\n{exc}\n\n"
            "Decide which is correct. Do not silently autogenerate over it."
        )


async def test_the_migration_is_the_only_head(database_url) -> None:
    """
    One head, or `alembic upgrade head` is ambiguous.

    Two heads is what a merge of two branches that each added a migration produces, and
    the symptom is a deployment that applies one of them and reports success.
    """
    from alembic.config import Config  # noqa: F401 - imported for the side-effect below
    from alembic.script import ScriptDirectory

    config = _alembic_config(database_url)
    heads = ScriptDirectory.from_config(config).get_heads()
    assert len(heads) == 1, f"expected one migration head, found {heads}"


async def test_every_table_lives_in_the_memory_schema(engine) -> None:
    """
    The decision that makes Memory's blast radius a grant rather than a data move.

    A table that lands in `public` by omission would be readable by every other
    service's role, and nothing else in the system would notice.
    """
    from sqlalchemy import text

    async with engine.connect() as conn:
        rows = await conn.execute(
            text(
                "SELECT table_name FROM information_schema.tables "
                "WHERE table_schema = 'memory' ORDER BY table_name"
            )
        )
        tables = {row[0] for row in rows}

    assert {"entities", "relationships", "task_history", "action_log"} <= tables


async def test_the_alembic_version_table_is_not_in_public(engine) -> None:
    """
    It lives in `memory` alongside what it versions.

    In `public` it would be a row every other service's role can see, and a second
    service's Alembic would collide with it.
    """
    from sqlalchemy import text

    async with engine.connect() as conn:
        in_memory = await conn.scalar(
            text("SELECT to_regclass('memory.alembic_version') IS NOT NULL")
        )
        in_public = await conn.scalar(
            text("SELECT to_regclass('public.alembic_version') IS NOT NULL")
        )

    assert in_memory is True
    assert in_public is False


async def test_the_orchestrators_tables_are_untouched(engine) -> None:
    """
    Memory's migration must never reach into `public`.

    `include_object` in `env.py` scopes autogenerate to the `memory` schema; without
    it, the first `--autogenerate` against a live database would emit a migration
    dropping another service's tables, and it would look reasonable in review.
    """
    from sqlalchemy import text

    async with engine.connect() as conn:
        rows = await conn.execute(
            text(
                "SELECT table_name FROM information_schema.tables " "WHERE table_schema = 'public'"
            )
        )
        public_tables = {row[0] for row in rows}

    assert not ({"entities", "relationships", "task_history", "action_log"} & public_tables)
